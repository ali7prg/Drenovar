"""metadata.json per species from the exported files (GLB headers, manifests, registry)."""
import json
import os
import struct
import sys
import importlib

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)


def glb_json(path):
    b = open(path, "rb").read(20)
    jlen = struct.unpack_from("<I", b, 12)[0]
    with open(path, "rb") as f:
        f.seek(20)
        return json.loads(f.read(jlen))


def tris(js):
    return sum(js["accessors"][p["indices"]]["count"] // 3 for m in js["meshes"] for p in m["primitives"])


def main():
    work, registry = sys.argv[1], json.load(open(sys.argv[2]))
    for sid in ("velkor", "tenerys", "kamneklyk", "dragor"):
        sp = importlib.import_module("species." + sid)
        o = os.path.join(work, sid, "out")
        man = json.load(open(os.path.join(o, "clip_manifest.json")))
        lods = {}
        for lod in (0, 1, 2):
            p = os.path.join(o, f"{sid}_lod{lod}.glb")
            js = glb_json(p)
            imgs = {}
            for im in js.get("images", []):
                imgs[im["name"]] = None
            lods[f"lod{lod}"] = {"file": os.path.basename(p), "bytes": os.path.getsize(p), "triangles": tris(js),
                                 "materials": [m["name"] for m in js["materials"]],
                                 "textures": [im["name"] for im in js["images"]]}
        js1 = glb_json(os.path.join(o, f"{sid}_lod1.glb"))
        skin = js1["skins"][0]
        sockets = [n["name"] for n in js1["nodes"] if n.get("name", "").startswith("socket_")]
        reg = registry["species"][sid]
        # GPU texture estimate for the Godot runtime (LOD1 + LOD2 maps, ASTC/BPTC 1 byte per texel, mips 4/3)
        sizes = {0: (2048, 1024), 1: (1024, 512), 2: (512, 256)}
        groups = len(sp.MATERIAL_NAMES)
        def tex_bytes(lod):
            c, o2 = sizes[lod]
            return groups * (2 * c * c + 2 * o2 * o2) * 4 / 3
        meta = {"id": sid, "name": sp.NAME, "version": "creatures-v2 1.0 (2026-11-17)", "units": "metre", "up": "+Y",
                "forward": "+X", "pivot": "ground, body centre", "authored_bounds_m": reg["authored_bounds_m"],
                "display_scale_in_game": reg["display_scale"], "battle_outline_m": reg["body"],
                "bones": len(skin["joints"]), "max_influences": 4, "sockets": sockets,
                "material_slots": list(sp.MATERIAL_NAMES.values()), "lods": lods,
                "clips": {k: {"name": v["name"], "frames": v["frames"], "length_s": v["length_s"], "loop": v["loop"],
                              "events": v["events"], **({"windows": v["windows"]} if "windows" in v else {}),
                              **({"speed_mps": v["speed_mps"]} if "speed_mps" in v else {}),
                              **({"motion_keys": list(v["motion"].keys())} if "motion" in v else {})}
                          for k, v in man["clips"].items()},
                "semantic_states": man["semantic_states"], "server_events": man["server_events"],
                "levels": reg["levels"], "emission_color": reg["emission_color"],
                "gpu_texture_estimate_mb": {"godot_runtime_lod1_lod2": round((tex_bytes(1) + tex_bytes(2)) / 1048576, 1),
                                            "lod0": round(tex_bytes(0) / 1048576, 1)},
                "compression": "none (core glTF 2.0 + KHR_materials_emissive_strength); Godot imports textures as VRAM-compressed (ASTC/ETC2 on iOS)",
                "licences": "All geometry, textures and animation generated by godot/art/creatures-v2 (DRENOVAR project). No third-party assets.",
                "provenance": "Procedural SDF sculpt + QuadriFlow/decimation + xatlas + Cycles bakes + procedural PBR + IK keyed clips"}
        with open(os.path.join(o, "metadata.json"), "w") as f:
            json.dump(meta, f, ensure_ascii=False, indent=1)
        print(sid, meta["bones"], {k: v["triangles"] for k, v in lods.items()}, meta["gpu_texture_estimate_mb"])


if __name__ == "__main__":
    main()
